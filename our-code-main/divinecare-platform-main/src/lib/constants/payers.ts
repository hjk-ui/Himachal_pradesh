export function payerLabel(id: string): string {
  return PAYER_LIST.find((p) => p.id === id)?.label ?? id
}

export function payersByGroup(): Record<PayerGroup, PayerEntry[]> {
  const out = {} as Record<PayerGroup, PayerEntry[]>
  for (const g of PAYER_GROUP_ORDER) out[g] = []
  for (const p of PAYER_LIST) out[p.group].push(p)
  return out
}

/** Prefix match: medicaid matches medicaid-md; exact match also OK */
export function payerAccepted(
  insuranceType: string | null | undefined,
  acceptedPayers: string[],
): boolean {
  if (!insuranceType?.trim()) return false
  const t = insuranceType.trim().toLowerCase()
  return acceptedPayers.some((p) => {
    const ap = p.toLowerCase()
    return ap === t || ap.startsWith(t + '-')
  })
}

