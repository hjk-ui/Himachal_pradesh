/**
 * Chart history digest kinds and role rules (Oct 25). Pure — safe to import from client components.
 */

export const CHART_DIGEST_KINDS = ['bh', 'medical'] as const;
export type ChartDigestKind = (typeof CHART_DIGEST_KINDS)[number];

export const DEFAULT_DIGEST_KIND: ChartDigestKind = 'bh';

/** Missing or empty → default `bh`; anything else that is not a known kind → null. */
export function parseDigestKind(value: string | null | undefined): ChartDigestKind | null {
  if (value === null || value === undefined || value === '') return DEFAULT_DIGEST_KIND;
  const v = value.trim().toLowerCase();
  return (CHART_DIGEST_KINDS as readonly string[]).includes(v) ? (v as ChartDigestKind) : null;
}

function roleOf(role: string | null | undefined): string {
  return (role ?? '').toUpperCase();
}

/** Clinic leadership: may view either kind without being on the care team. */
export const LEADERSHIP_ROLES = ['ADMIN', 'DIRECTOR', 'PRACTICE_DIRECTOR'] as const;

export function isLeadershipRole(role: string | null | undefined): boolean {
  return (LEADERSHIP_ROLES as readonly string[]).includes(roleOf(role));
}

/** Medical history viewers: medical team, psychiatric prescribers, and leadership. */
export const MEDICAL_VIEW_ROLES = [
  'PHYSICIAN',
  'MEDICAL_NP',
  'MEDICAL_ASSISTANT',
  'PSYCHIATRIST',
  'NP',
  ...LEADERSHIP_ROLES,
] as const;

/** Medical history may be regenerated by these roles, and only when on the care team. */
export const MEDICAL_REGENERATE_ROLES = ['PHYSICIAN', 'MEDICAL_NP'] as const;

/**
 * Behavioral health history viewers: roles that already receive progress-note bodies.
 * Medical roles do not (see chartVisibility), so they do not get a BH digest either.
 */
export const BH_VIEW_ROLES = [
  'THERAPIST',
  'CLINICIAN',
  'PSYCHIATRIST',
  'NP',
  'CASE_MANAGER',
  'PRP_SPECIALIST',
  ...LEADERSHIP_ROLES,
] as const;

/** BH history may be regenerated by clinicians who can view it, on the care team (leadership: any client). */
export const BH_REGENERATE_ROLES = [
  'THERAPIST',
  'CLINICIAN',
  'PSYCHIATRIST',
  'NP',
  ...LEADERSHIP_ROLES,
] as const;

export function canViewDigestKind(role: string | null | undefined, kind: ChartDigestKind): boolean {
  const r = roleOf(role);
  const list: readonly string[] = kind === 'medical' ? MEDICAL_VIEW_ROLES : BH_VIEW_ROLES;
  return list.includes(r);
}

export function canRegenerateDigestKind(
  role: string | null | undefined,
  kind: ChartDigestKind
): boolean {
  const r = roleOf(role);
  const list: readonly string[] = kind === 'medical' ? MEDICAL_REGENERATE_ROLES : BH_REGENERATE_ROLES;
  return list.includes(r);
}

/** Medical assistants see a subset of the medical digest. */
export const MA_SECTION_KEYS = ['allergies', 'medications', 'vitals', 'preventiveDue'] as const;

export function isMedicalAssistantRole(role: string | null | undefined): boolean {
  return roleOf(role) === 'MEDICAL_ASSISTANT';
}

// ── Content shape ───────────────────────────────────────────────────────────────

export type DigestSource = {
  /** Short citation id used inside content, e.g. S3 */
  id: string;
  /** Record type, e.g. diagnosis, medication, note, appointment, lab, vital, allergy, care_gap */
  type: string;
  label: string;
  /** ISO date of the underlying record, when it has one */
  date: string | null;
};

export type DigestItem = {
  text: string;
  /** Source ids from `sources`; an item without a valid citation is never stored */
  citations: string[];
};

export type DigestSection = {
  key: string;
  title: string;
  items: DigestItem[];
};

export type DigestContent = {
  version: 1;
  sections: DigestSection[];
  sources: DigestSource[];
};

export const BH_SECTIONS: ReadonlyArray<{ key: string; title: string }> = [
  { key: 'diagnoses', title: 'Diagnoses' },
  { key: 'medications', title: 'Medications' },
  { key: 'courseOfCare', title: 'Course of care' },
  { key: 'recentVisits', title: 'Recent visits' },
];

export const MEDICAL_SECTIONS: ReadonlyArray<{ key: string; title: string }> = [
  { key: 'allergies', title: 'Allergies' },
  { key: 'medications', title: 'Medications' },
  { key: 'vitals', title: 'Vitals' },
  { key: 'problems', title: 'Medical problems' },
  { key: 'labs', title: 'Labs' },
  { key: 'preventiveDue', title: 'Preventive care due' },
  { key: 'recentVisits', title: 'Recent visits' },
];

export function sectionsForKind(kind: ChartDigestKind) {
  return kind === 'medical' ? MEDICAL_SECTIONS : BH_SECTIONS;
}
