/**
 * Role-home widgets fed by GET /api/dashboard/home. Every number is a server count over real
 * records; hovering a tile shows its source. Nothing here is estimated or generated by a model.
 */

const TONE: Record<HomeTileTone, Tone> = {
  purple: 'brand',
  red: 'danger',
  amber: 'warning',
  teal: 'info',
  blue: 'brand',
  slate: 'neutral',
  green: 'success',
};

export function formatTileValue(tile: Pick<HomeTile, 'key' | 'value'>): string {
  if (tile.value == null) return '—';
  if (/^(paid_7d|collections_mtd)$/.test(tile.key)) {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }).format(tile.value / 100);
  }
  return tile.value.toLocaleString('en-US');
}

/** One count tile. The whole tile links to its list; the source is the hover title. */
export function HomeTileCard({ tile, icon }: { tile: HomeTile; icon?: React.ReactNode }) {
  const tone = TONE[tile.tone] ?? TONE.slate;
  return (
    <div title={tile.source} className="min-w-0">
      <UiStatCard icon={icon} label={tile.label} value={formatTileValue(tile)} hint={tile.sub} href={tile.href} tone={tone} className="h-full" />
    </div>
  );
}

/** Role counter tiles (active clients, new clients, prescriptions, ...) in the given order; missing ones are skipped */
export function CounterTiles({ keys, icons = {} }: { keys: string[]; icons?: Record<string, React.ReactNode> }) {
  const { data } = useDashboardHome();
  const tiles = keys
    .map((k) => (data?.counters as Record<string, HomeTile | undefined> | undefined)?.[k])
    .filter((t): t is HomeTile => Boolean(t));
  if (!tiles.length) return null;
  return (
    <>
      {tiles.map((t) => (
        <HomeTileCard key={t.key} tile={t} icon={icons[t.key]} />
      ))}
    </>
  );
}

export function useCounter(key: string): HomeTile | null {
  const { data } = useDashboardHome();
  return ((data?.counters as Record<string, HomeTile | undefined> | undefined)?.[key]) ?? null;
}

const SEVERITY: Record<HomeInsight['severity'], Tone> = {
  critical: 'danger',
  high: 'warning',
  routine: 'neutral',
};

/**
 * Caseload Health: counts for the signed-in user's caseload (or, for leadership, the practice /
 * selected location) plus rule-based findings over the same numbers.
 */
export function CaseloadHealthPanel({ title }: { title?: string }) {
  const { data, loading, error } = useDashboardHome();
  const health = data?.caseloadHealth ?? null;
  if (error) {
    return (
      <Alert tone="danger">Caseload health could not be loaded: {error}</Alert>
    );
  }
  if (loading && !health) {
    return <div className={cardClasses}><LoadingState label="Loading caseload health…" /></div>;
  }
  if (!health) return null;
  const heading = title ?? (health.scope === 'caseload' ? 'Caseload Health' : 'Practice Caseload Health');
  return (
    <div className="grid grid-cols-1 gap-4 xl:grid-cols-3">
      <section className={`${cardClasses} min-w-0 xl:col-span-2`}>
        <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-200 px-5 py-3">
          <div className="flex items-center gap-2">
            <HeartPulse aria-hidden size={16} className="text-rose-700" />
            <h2 className="text-sm font-semibold text-slate-900">{heading}</h2>
          </div>
          <p className="text-xs text-slate-500">
            {health.scope === 'caseload' ? 'Your assigned active clients' : 'Active clients in this view'}
            {health.hiddenSensitiveClients ? ` · ${health.hiddenSensitiveClients} protected not counted` : ''}
          </p>
        </div>
        <div className="grid grid-cols-1 gap-3 p-4 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4">
          {health.tiles.map((t) => (
            <HomeTileCard key={t.key} tile={t} />
          ))}
        </div>
        {health.notes.length ? (
          <ul className="border-t border-slate-100 px-5 py-2 text-xs text-slate-500">
            {health.notes.map((n) => (
              <li key={n}>{n}</li>
            ))}
          </ul>
        ) : null}
      </section>

      <section className={`${cardClasses} min-w-0`}>
        <div className="flex items-center gap-2 border-b border-slate-200 px-5 py-3">
          <Lightbulb aria-hidden size={16} className="text-blue-700" />
          <h2 className="text-sm font-semibold text-slate-900">What needs attention</h2>
        </div>
        {health.insights.length === 0 ? (
          <EmptyState compact title="No open findings from these counts." />
        ) : (
          <ul className="divide-y divide-slate-100">
            {health.insights.slice(0, 8).map((i) => {
              const inner = (
                <div className="flex items-start justify-between gap-2">
                  <div className="min-w-0">
                    <p className="break-words text-sm font-semibold text-slate-900">{i.text}</p>
                    <p className="mt-0.5 text-xs text-slate-500">{i.basis}</p>
                  </div>
                  <StatusBadge tone={SEVERITY[i.severity]} className="shrink-0">{i.severity}</StatusBadge>
                </div>
              );
              return (
                <li key={i.id}>
                  {i.href ? (
                    <Link href={i.href} className="block px-5 py-3 hover:bg-slate-50">
                      {inner}
                    </Link>
                  ) : (
                    <div className="px-5 py-3">{inner}</div>
                  )}
                </li>
              );
            })}
          </ul>
        )}
        <p className="border-t border-slate-100 px-5 py-2 text-xs text-slate-500">Rules over the counts on the left. Not a prediction.</p>
      </section>
    </div>
  );
}

const STATUS_LABEL: Record<ScheduleStatus, string> = {
  scheduled: 'Scheduled',
  'checked-in': 'Checked in',
  'in-session': 'In session',
  completed: 'Completed',
  'no-show': 'No-show',
  'late-cancel': 'Late cancel',
};
const STATUS_BADGE: Record<ScheduleStatus, Tone> = {
  scheduled: 'neutral',
  'checked-in': 'info',
  'in-session': 'brand',
  completed: 'success',
  'no-show': 'warning',
  'late-cancel': 'warning',
};

function ScheduleCountsBar({ s }: { s: TodaySchedule }) {
  const items = [
    { label: 'Total', value: s.counts.total },
    { label: 'Checked in', value: s.counts.checkedIn },
    { label: 'In session', value: s.counts.inSession },
    { label: 'Completed', value: s.counts.completed },
    { label: 'No-show', value: s.counts.noShow },
    { label: 'Remaining', value: s.counts.remaining },
  ];
  return (
    <div className="grid grid-cols-2 gap-2 border-b border-slate-100 px-4 py-3 sm:grid-cols-3 sm:px-5 lg:grid-cols-6">
      {items.map((i) => (
        <div key={i.label} className="rounded-lg bg-slate-50 px-2 py-1.5 text-center">
          <p className="text-base font-semibold tabular-nums text-slate-900">{i.value}</p>
          <p className="text-xs font-medium text-slate-500">{i.label}</p>
        </div>
      ))}
    </div>
  );
}

function ScheduleRowView({ r, zone, showClinician, showLocation, due }: { r: ScheduleRow; zone: string; showClinician: boolean; showLocation: boolean; due?: ConsentsDue }) {
  return (
    <tr className="hover:bg-slate-50">
      <td className="whitespace-nowrap px-4 py-3 text-sm font-semibold tabular-nums text-slate-900 sm:px-5">
        {formatWallClock(r.startTime)}–{formatWallClock(r.endTime)} <span className="text-[11px] font-medium text-slate-500">{zone}</span>
      </td>
      <td className="px-4 py-3 sm:px-5">
        {r.clientId ? (
          <Link href={`/dashboard/clients/${encodeURIComponent(r.clientId)}`} className="text-sm font-semibold text-slate-900 hover:text-blue-700">
            {r.clientName}
          </Link>
        ) : (
          <span className="text-sm font-semibold text-slate-900">{r.clientName}</span>
        )}
        {r.label ? <AppointmentLabelChip label={r.label} size="xs" className="mt-0.5" /> : null}
        {due ? <div><ConsentsDueBadge clientId={r.clientId} due={due} /></div> : null}
      </td>
      {showClinician ? <td className="px-4 py-3 text-xs text-slate-600 sm:px-5">{r.clinicianName || 'Unassigned'}</td> : null}
      <td className="px-4 py-3 text-xs text-slate-500 sm:px-5">{r.type}</td>
      <td className="px-4 py-3 sm:px-5">
        <StatusBadge tone={r.isVirtual ? 'info' : 'neutral'}>
          {r.isVirtual ? <Video aria-hidden size={12} /> : null}
          {r.isVirtual ? 'Telehealth' : 'In person'}
        </StatusBadge>
      </td>
      {showLocation ? (
        <td className="px-4 py-3 text-xs text-slate-500 sm:px-5" title={r.locationInferred ? "Client's home location (not recorded on the appointment)" : undefined}>
          {r.locationName ? `${r.locationName}${r.locationInferred ? '*' : ''}` : '—'}
        </td>
      ) : null}
      <td className="px-4 py-3 sm:px-5">
        <StatusBadge tone={STATUS_BADGE[r.status]}>{STATUS_LABEL[r.status]}</StatusBadge>
      </td>
    </tr>
  );
}

/**
 * Today's schedule on the practice clock: every non-cancelled appointment starting between
 * practice midnight and the next practice midnight, sorted by start time.
 */
export function TodayScheduleCard({
  title = "Today's Schedule",
  limit,
  showClinician = true,
  showLocation = true,
  consentsDue = false,
}: {
  title?: string;
  limit?: number;
  showClinician?: boolean;
  showLocation?: boolean;
  /** Check-in board: badge clients with consents needed before the visit */
  consentsDue?: boolean;
}) {
  const { data, loading, error } = useDashboardHome();
  const s = data?.schedule ?? null;
  const zone = s ? practiceZoneLabel(s.timeZone) : '';
  const rows = s ? (limit ? s.rows.slice(0, limit) : s.rows) : [];
  const due = useConsentsDue(rows.map((r) => r.clientId), consentsDue);
  return (
    <section className={`overflow-hidden ${cardClasses}`}>
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 px-4 py-4 sm:px-5">
        <div className="flex items-center gap-2">
          <CalendarDays aria-hidden size={16} className="text-blue-700" />
          <div>
            <h2 className="text-sm font-semibold text-slate-900">{title}</h2>
            {s ? (
              <p className="text-xs text-slate-500">
                {formatPracticeDate(s.windowStart, s.timeZone)} · {zone} · {s.scope === 'caseload' ? 'Your caseload' : s.locationId ? 'Selected location' : 'All clinicians'}
              </p>
            ) : null}
          </div>
        </div>
        <Link href="/dashboard/appointments" className="shrink-0 text-xs font-semibold text-blue-700 hover:underline">
          Open schedule
        </Link>
      </div>
      {error ? (
        <ErrorState title="Today's schedule could not be loaded" description={error} />
      ) : loading && !s ? (
        <LoadingState label="Loading today's schedule…" rows={4} />
      ) : !s ? (
        <p className="p-6 text-sm text-slate-500">No schedule access for this role.</p>
      ) : (
        <>
          {s.locationApplied ? null : (
            <p className="border-b border-amber-100 bg-amber-50 px-5 py-2 text-xs text-amber-800">
              The selected location is not set up for this practice, so all locations are shown.
            </p>
          )}
          <ScheduleCountsBar s={s} />
          {rows.length === 0 ? (
            <EmptyState compact title="No appointments today." description="Booked visits for today appear here." />
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full min-w-[640px] text-sm">
                <thead>
                  <tr className="border-b border-slate-200 bg-slate-50 text-xs font-semibold text-slate-600">
                    <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Time</th>
                    <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Client</th>
                    {showClinician ? <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Clinician</th> : null}
                    <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Visit type</th>
                    <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Format</th>
                    {showLocation ? <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Location</th> : null}
                    <th scope="col" className="px-4 py-2.5 text-left sm:px-5">Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {rows.map((r) => (
                    <ScheduleRowView key={r.id} r={r} zone={zone} showClinician={showClinician} showLocation={showLocation} due={consentsDue ? due : undefined} />
                  ))}
                </tbody>
              </table>
              {limit && s.rows.length > limit ? (
                <p className="border-t border-slate-100 px-5 py-2 text-xs text-slate-500">
                  Showing {limit} of {s.rows.length}.{' '}
                  <Link href="/dashboard/appointments" className="font-semibold text-blue-700 hover:underline">
                    See all
                  </Link>
                </p>
              ) : null}
            </div>
          )}
        </>
      )}
    </section>
  );
}

/** Today's schedule counts as tiles (for homes that keep their own schedule list) */
export function useTodayScheduleCounts() {
  const { data } = useDashboardHome();
  return data?.schedule ?? null;
}

